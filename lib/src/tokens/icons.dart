/// Icon size tokens from the ValiDS design system
/// (https://valids-componentes.services-valid.com.br → Ícones/Referência →
/// Tamanhos).
class ValidsIconSize {
  ValidsIconSize._();

  /// `size-md` → 16px — "usar com cautela" (contextos muito compactos).
  static const double md = 16;

  /// `size-lg` → 24px — tamanho recomendado pelo DS.
  static const double lg = 24;

  /// `size-xl` → 32px.
  static const double xl = 32;

  /// `size-2xl` → 40px.
  static const double xl2 = 40;
}
