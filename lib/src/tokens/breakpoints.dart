/// Responsive breakpoint tokens from the ValiDS design system
/// (Tailwind default screens, used by DS components such as the Toast
/// positioning).
class ValidsBreakpoints {
  ValidsBreakpoints._();

  /// `sm` → 640px
  static const double sm = 640;

  /// `md` → 768px
  static const double md = 768;

  /// `lg` → 1024px
  static const double lg = 1024;

  /// `xl` → 1280px
  static const double xl = 1280;

  /// `2xl` → 1536px
  static const double xl2 = 1536;
}
